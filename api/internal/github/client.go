package github

import (
	"context"
	"fmt"
	"net/http"
	"time"

	"github.com/bradleyfalzon/ghinstallation/v2"
	gh "github.com/google/go-github/v66/github"
	"github.com/jakkayy/kuberlauncher/api/internal/generator"
	"github.com/jakkayy/kuberlauncher/api/internal/httpx"
	"golang.org/x/oauth2"
)

type Client struct {
	gh    *gh.Client
	owner string
	// org is true when owner is an organization; repos are then created
	// under the org instead of the authenticated user.
	org bool
}

// New authenticates with a personal access token. Set ownerIsOrg when owner
// is an organization.
func New(token, owner string, ownerIsOrg bool) *Client {
	ts := oauth2.StaticTokenSource(&oauth2.Token{AccessToken: token})
	tc := &http.Client{Transport: &oauth2.Transport{Source: ts, Base: httpx.NewRetryTransport(nil)}}
	return &Client{
		gh:    gh.NewClient(tc),
		owner: owner,
		org:   ownerIsOrg,
	}
}

// NewApp authenticates as a GitHub App installation. Installation tokens are
// short-lived and refreshed automatically; permissions come from the App
// settings instead of a user's PAT. The installation must belong to the org owner.
func NewApp(appID, installationID int64, privateKey []byte, owner string) (*Client, error) {
	tr, err := ghinstallation.New(httpx.NewRetryTransport(nil), appID, installationID, privateKey)
	if err != nil {
		return nil, fmt.Errorf("github app transport: %w", err)
	}
	return &Client{
		gh:    gh.NewClient(&http.Client{Transport: tr}),
		owner: owner,
		org:   true,
	}, nil
}

// CreateRepo creates a new GitHub repository and pushes all generated files.
// Returns the HTML URL of the created repo.
func (c *Client) CreateRepo(ctx context.Context, slug string, files []generator.GeneratedFile) (string, error) {
	private := false
	org := "" // "" creates the repo for the authenticated user
	if c.org {
		org = c.owner
	}
	repo, _, err := c.gh.Repositories.Create(ctx, org, &gh.Repository{
		Name:        gh.String(slug),
		Description: gh.String(fmt.Sprintf("Generated by kuberLaunch — %s service", slug)),
		Private:     &private,
		AutoInit:    gh.Bool(true), // creates initial commit so blob API works
	})
	if err != nil {
		return "", fmt.Errorf("create repo: %w", err)
	}

	if err := c.pushFiles(ctx, slug, files); err != nil {
		return *repo.HTMLURL, fmt.Errorf("push files: %w", err)
	}

	return *repo.HTMLURL, nil
}

// pushFiles commits all generated files to main in a single commit using
// the Git Tree API. Files not in files are kept: the new tree is based on the
// current one, so user code is never removed.
func (c *Client) pushFiles(ctx context.Context, repo string, files []generator.GeneratedFile) error {
	// Get the latest commit SHA on main — empty repo won't have this ref
	ref, _, err := c.gh.Git.GetRef(ctx, c.owner, repo, "refs/heads/main")
	if err != nil {
		// Empty repo: ใช้ Contents API (รองรับ repo ที่ยังไม่มี commit)
		return c.pushFilesViaContents(ctx, repo, files)
	}
	sha, err := c.commitFiles(ctx, repo, ref.Object.GetSHA(), files, "chore: sync project scaffold from kuberLaunch")
	if err != nil {
		return err
	}
	_, _, err = c.gh.Git.UpdateRef(ctx, c.owner, repo, &gh.Reference{
		Ref:    gh.String("refs/heads/main"),
		Object: &gh.GitObject{SHA: gh.String(sha)},
	}, false)
	return err
}

// commitFiles creates a commit on top of parentSHA that adds or replaces
// files, keeping everything else in the parent tree. Returns the commit SHA.
func (c *Client) commitFiles(ctx context.Context, repo, parentSHA string, files []generator.GeneratedFile, message string) (string, error) {
	parent, _, err := c.gh.Git.GetCommit(ctx, c.owner, repo, parentSHA)
	if err != nil {
		return "", fmt.Errorf("get parent commit: %w", err)
	}

	var treeEntries []*gh.TreeEntry
	for _, f := range files {
		blob, _, err := c.gh.Git.CreateBlob(ctx, c.owner, repo, &gh.Blob{
			Content:  gh.String(f.Content),
			Encoding: gh.String("utf-8"),
		})
		if err != nil {
			return "", fmt.Errorf("create blob %s: %w", f.Path, err)
		}
		treeEntries = append(treeEntries, &gh.TreeEntry{
			Path: gh.String(f.Path),
			Mode: gh.String("100644"),
			Type: gh.String("blob"),
			SHA:  blob.SHA,
		})
	}

	tree, _, err := c.gh.Git.CreateTree(ctx, c.owner, repo, parent.GetTree().GetSHA(), treeEntries)
	if err != nil {
		return "", fmt.Errorf("create tree: %w", err)
	}

	commit, _, err := c.gh.Git.CreateCommit(ctx, c.owner, repo, &gh.Commit{
		Message: gh.String(message),
		Tree:    tree,
		Parents: []*gh.Commit{{SHA: gh.String(parentSHA)}},
	}, &gh.CreateCommitOptions{})
	if err != nil {
		return "", fmt.Errorf("create commit: %w", err)
	}
	return commit.GetSHA(), nil
}

// pushFilesViaContents pushes files one-by-one using the Contents API.
// Used for empty repos where the Git Trees API is unavailable.
func (c *Client) pushFilesViaContents(ctx context.Context, repo string, files []generator.GeneratedFile) error {
	for _, f := range files {
		_, _, err := c.gh.Repositories.CreateFile(ctx, c.owner, repo, f.Path, &gh.RepositoryContentFileOptions{
			Message: gh.String("chore: initial project scaffold by kuberLaunch"),
			Content: []byte(f.Content),
		})
		if err != nil {
			return fmt.Errorf("create file %s: %w", f.Path, err)
		}
	}
	return nil
}

func (c *Client) Owner() string { return c.owner }

// PushFiles pushes all generated files to an existing repo as a new commit.
func (c *Client) PushFiles(ctx context.Context, slug string, files []generator.GeneratedFile) error {
	return c.pushFiles(ctx, slug, files)
}

// RepoExists returns true if the repo already exists under the owner.
func (c *Client) RepoExists(ctx context.Context, slug string) bool {
	_, resp, _ := c.gh.Repositories.Get(ctx, c.owner, slug)
	return resp != nil && resp.StatusCode == 200
}

// TriggerWorkflow dispatches a workflow_dispatch event for the CI workflow.
// Returns the run ID of the triggered workflow run.
func (c *Client) TriggerWorkflow(ctx context.Context, slug, branch string) error {
	_, err := c.gh.Actions.CreateWorkflowDispatchEventByFileName(
		ctx, c.owner, slug, "ci.yml",
		gh.CreateWorkflowDispatchEventRequest{Ref: branch},
	)
	return err
}

// WorkflowRun is the subset of a GitHub Actions run that deployments track.
type WorkflowRun struct {
	ID         int64
	Status     string // queued | in_progress | completed
	Conclusion string // empty until completed
	HeadSHA    string
}

func toWorkflowRun(r *gh.WorkflowRun) *WorkflowRun {
	return &WorkflowRun{
		ID:         r.GetID(),
		Status:     r.GetStatus(),
		Conclusion: r.GetConclusion(),
		HeadSHA:    r.GetHeadSHA(),
	}
}

// FindDispatchedRun returns the earliest workflow_dispatch run of ci.yml on branch
// created at or after since, or nil if GitHub has not created it yet.
func (c *Client) FindDispatchedRun(ctx context.Context, slug, branch string, since time.Time) (*WorkflowRun, error) {
	runs, _, err := c.gh.Actions.ListWorkflowRunsByFileName(
		ctx, c.owner, slug, "ci.yml",
		&gh.ListWorkflowRunsOptions{
			Event:       "workflow_dispatch",
			Branch:      branch,
			Created:     ">=" + since.UTC().Format(time.RFC3339),
			ListOptions: gh.ListOptions{PerPage: 20},
		},
	)
	if err != nil {
		return nil, err
	}
	if len(runs.WorkflowRuns) == 0 {
		return nil, nil
	}
	// Runs are returned newest first; the earliest one after since is ours.
	return toWorkflowRun(runs.WorkflowRuns[len(runs.WorkflowRuns)-1]), nil
}

// GetWorkflowRun returns a workflow run by ID.
func (c *Client) GetWorkflowRun(ctx context.Context, slug string, runID int64) (*WorkflowRun, error) {
	r, _, err := c.gh.Actions.GetWorkflowRunByID(ctx, c.owner, slug, runID)
	if err != nil {
		return nil, err
	}
	return toWorkflowRun(r), nil
}

// GetFileContent returns the decoded content of a file in the repo.
func (c *Client) GetFileContent(ctx context.Context, slug, path string) (string, error) {
	file, _, _, err := c.gh.Repositories.GetContents(ctx, c.owner, slug, path, nil)
	if err != nil {
		return "", fmt.Errorf("get file content: %w", err)
	}
	content, err := file.GetContent()
	if err != nil {
		return "", fmt.Errorf("decode file content: %w", err)
	}
	return content, nil
}

// EnsureWebhook registers a workflow_run webhook delivering to url, unless a
// hook with that URL already exists.
func (c *Client) EnsureWebhook(ctx context.Context, slug, url, secret string) error {
	hooks, _, err := c.gh.Repositories.ListHooks(ctx, c.owner, slug, nil)
	if err != nil {
		return fmt.Errorf("list hooks: %w", err)
	}
	for _, h := range hooks {
		if h.Config != nil && h.Config.GetURL() == url {
			return nil
		}
	}
	_, _, err = c.gh.Repositories.CreateHook(ctx, c.owner, slug, &gh.Hook{
		Events: []string{"workflow_run"},
		Active: gh.Bool(true),
		Config: &gh.HookConfig{
			URL:         gh.String(url),
			ContentType: gh.String("json"),
			Secret:      gh.String(secret),
		},
	})
	if err != nil {
		return fmt.Errorf("create hook: %w", err)
	}
	return nil
}

// PullRequest is the state of a pull request opened by kuberLaunch.
type PullRequest struct {
	URL    string
	State  string // open | closed
	Merged bool
}

// FindPullRequest returns the most recent pull request from head branch, or nil.
func (c *Client) FindPullRequest(ctx context.Context, slug, head string) (*PullRequest, error) {
	prs, _, err := c.gh.PullRequests.List(ctx, c.owner, slug, &gh.PullRequestListOptions{
		Head:        c.owner + ":" + head,
		State:       "all",
		ListOptions: gh.ListOptions{PerPage: 1},
	})
	if err != nil {
		return nil, err
	}
	if len(prs) == 0 {
		return nil, nil
	}
	pr := prs[0]
	return &PullRequest{URL: pr.GetHTMLURL(), State: pr.GetState(), Merged: !pr.GetMergedAt().IsZero()}, nil
}

// OpenPullRequest commits files onto a new branch cut from main and opens a
// pull request into main. The branch is reset if it already exists.
func (c *Client) OpenPullRequest(ctx context.Context, slug, branch, title, body string, files []generator.GeneratedFile) (*PullRequest, error) {
	main, _, err := c.gh.Git.GetRef(ctx, c.owner, slug, "refs/heads/main")
	if err != nil {
		return nil, fmt.Errorf("get main: %w", err)
	}
	sha, err := c.commitFiles(ctx, slug, main.Object.GetSHA(), files, title)
	if err != nil {
		return nil, err
	}
	ref := &gh.Reference{Ref: gh.String("refs/heads/" + branch), Object: &gh.GitObject{SHA: gh.String(sha)}}
	if _, _, err := c.gh.Git.CreateRef(ctx, c.owner, slug, ref); err != nil {
		if _, _, err := c.gh.Git.UpdateRef(ctx, c.owner, slug, ref, true); err != nil {
			return nil, fmt.Errorf("create branch %s: %w", branch, err)
		}
	}
	pr, _, err := c.gh.PullRequests.Create(ctx, c.owner, slug, &gh.NewPullRequest{
		Title: gh.String(title),
		Head:  gh.String(branch),
		Base:  gh.String("main"),
		Body:  gh.String(body),
	})
	if err != nil {
		return nil, fmt.Errorf("create pull request: %w", err)
	}
	return &PullRequest{URL: pr.GetHTMLURL(), State: pr.GetState()}, nil
}

// ArchiveRepo makes a repository read-only while keeping its code and history.
func (c *Client) ArchiveRepo(ctx context.Context, slug string) error {
	_, _, err := c.gh.Repositories.Edit(ctx, c.owner, slug, &gh.Repository{Archived: gh.Bool(true)})
	return err
}

// UpdateFile updates a single file in the repo via the Contents API.
func (c *Client) UpdateFile(ctx context.Context, slug, path, content, message string) error {
	// Get current file SHA (needed for updates)
	file, _, _, err := c.gh.Repositories.GetContents(ctx, c.owner, slug, path, nil)
	if err != nil {
		return fmt.Errorf("get file sha: %w", err)
	}

	_, _, err = c.gh.Repositories.UpdateFile(ctx, c.owner, slug, path, &gh.RepositoryContentFileOptions{
		Message: gh.String(message),
		Content: []byte(content),
		SHA:     file.SHA,
	})
	return err
}
